function getInitialLanguage() {
  const saved = localStorage.getItem("edp-lang");
  if (saved && content[saved]) {
    return saved;
  }

  const browserLang = navigator.language.toLowerCase();
  if (browserLang.startsWith("de")) {
    return "de";
  }
  if (browserLang.startsWith("zh")) {
    return "zh";
  }
  return "en";
}

